HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
APP_JS = os.path.join(ROOT, "app", "js")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "supabase", "functions", "notify", "schedule.js")

# 01-04: program, nutrition, dates, state/timeline. 06: shared helpers. 09: autoVal/isDone (pure).
FILES = ["01-program.js", "02-nutrition.js", "03-dates.js", "04-state.js", "06-helpers.js", "09-score.js"]

PRELUDE = r"""// GENERATED by pwa/build-schedule.py from app/js/{files}. Do not edit by hand; rebuild instead.
// Lean Loken program logic for the notify Edge Function (ES module; Deno or Node).
/* ---------- browser stubs (module-scoped; nothing leaks to globalThis) ---------- */
const __noop = () => {};
const __el = () => ({ style: {}, dataset: {}, classList: { add: __noop, remove: __noop, toggle: __noop }, appendChild: __noop, remove: __noop, setAttribute: __noop, querySelector: () => null, querySelectorAll: () => [] });
const document = { querySelector: () => null, querySelectorAll: () => [], createElement: __el, addEventListener: __noop, body: __el(), activeElement: null, visibilityState: "visible" };
const __mem = new Map();
const localStorage = { getItem: (k) => (__mem.has(k) ? __mem.get(k) : null), setItem: (k, v) => { __mem.set(k, String(v)); }, removeItem: (k) => { __mem.delete(k); } };
const window = { document, localStorage, addEventListener: __noop, matchMedia: () => ({ matches: false }) };
const addEventListener = __noop;
"""

API = r"""
/* =========================================================
   SERVER API (appended by pwa/build-schedule.py)
   ========================================================= */
const NOTIFY_DEFAULTS = { meals: true, training: true, weigh: true, evening: true, caffeine: false };
const NOTIFY_ALIASES = { weighin: "weigh", water: "weigh", train: "training", meal: "meals" };
const WATER_NUDGES = [660, 900];          // 11:00 and 15:00 local, when behind pace
const EVENING_LOG = 1230;                 // 20:30 local
const DEFAULT_TZ = "America/Los_Angeles";

/* Load the user's docs. settingsDoc: the raw `settings` doc data. dayDocs: {"YYYY-MM-DD" | "d-YYYY-MM-DD": dayData}. */
function setState(settingsDoc, dayDocs) {
  S.set = normSet(isObj(settingsDoc) ? clone(settingsDoc) : {});
  S.days = {};
  if (isObj(dayDocs)) Object.keys(dayDocs).forEach((id) => {
    const k = id.startsWith("d-") ? id.slice(2) : id;
    if (validKey(k) && dayDocs[id] != null) S.days[k] = normDay(clone(dayDocs[id]));
  });
  return S;
}

/* ---------- time zone math (never uses the server's local zone) ---------- */
const __fmts = {};
function safeTz(tz) {
  if (typeof tz !== "string" || !tz) return DEFAULT_TZ;
  try { new Intl.DateTimeFormat("en-US", { timeZone: tz }); return tz; } catch (e) { return DEFAULT_TZ; }
}
/* Wall-clock parts of an instant in tz: {key:"YYYY-MM-DD", min: minutes after local midnight, sec}. */
function tzParts(date, tz) {
  tz = safeTz(tz);
  const f = __fmts[tz] || (__fmts[tz] = new Intl.DateTimeFormat("en-US", { timeZone: tz, year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", second: "2-digit", hourCycle: "h23" }));
  const p = {};
  for (const x of f.formatToParts(date)) p[x.type] = x.value;
  const h = (+p.hour) % 24;
  return { key: `${p.year}-${p.month}-${p.day}`, min: h * 60 + (+p.minute), sec: +p.second };
}
const __toDate = (x) => (x instanceof Date ? x : x == null ? new Date() : new Date(x));
function todayKeyInTz(tz, nowISO) { return tzParts(__toDate(nowISO), tz).key; }
function nowInTz(tz, nowISO) { return tzParts(__toDate(nowISO), tz); }
/* Local wall time (date key + minutes after midnight, may exceed 1440) in tz → UTC Date. */
function localToUtc(k, min, tz) {
  const [y, mo, d] = k.split("-").map(Number);
  const want = Date.UTC(y, mo - 1, d, 0, 0) + min * 60000;   // the wall time, read as if it were UTC
  let t = want;
  for (let i = 0; i < 3; i++) {
    const p = tzParts(new Date(t), tz), [py, pm, pd] = p.key.split("-").map(Number);
    const seen = Date.UTC(py, pm - 1, pd, 0, 0) + p.min * 60000;
    if (seen === want) break;
    t += want - seen;
  }
  return new Date(t);
}

/* ---------- notification preferences ---------- */
function notifyPrefs(raw) {
  const n = isObj(raw) && isObj(raw.notify) ? raw.notify : {};
  const o = Object.assign({}, NOTIFY_DEFAULTS);
  Object.keys(n).forEach((k0) => {
    const k = NOTIFY_ALIASES[k0] || k0;
    if (k in NOTIFY_DEFAULTS && typeof n[k0] === "boolean" && !(k0 !== k && typeof n[k] === "boolean")) o[k] = n[k0];
  });
  o.enabled = !(n.enabled === false || n.on === false || (isObj(raw) && raw.notifyOn === false));
  return o;
}
function leadOf(raw, lead) {
  const v = lead != null ? +lead : isObj(raw) && raw.notifyLead != null ? +raw.notifyLead : isObj(raw) && isObj(raw.notify) && raw.notify.lead != null ? +raw.notify.lead : 15;
  return isFinite(v) ? Math.min(120, Math.max(0, Math.round(v))) : 15;
}

/* ---------- message copy ---------- */
const __short = (l) => String(l).replace(/\s*\(.*\)\s*$/, "").split(",")[0].trim();
function mealBody(r, d) {
  const alt = d && isObj(d.mealsAlt) ? d.mealsAlt[r.id] : null;
  if (alt && alt.text) return String(alt.text).slice(0, 160);
  const items = (r.meal && r.meal.items) || [];
  const s = items.filter((i) => i.qty && i.qty !== "any").map((i) => `${__short(i.label)} ${String(i.qty).split(" · ")[0]}`).join(" · ");
  return s || r.detail || "";
}
function trainPart(r, pl, k) {
  const s = pl.sch;
  if (r.id === "lift") {
    const n = WORKOUTS[s.lift].ex.filter((e) => !e.optional).length;
    return `${wkName(s.lift)} — ${n} exercises, ~${Math.round(r.end - r.t)} min`;
  }
  if (r.id === "intervals") {
    const ip = intervalPlan(k);
    return ip.mode === "bike" ? `Peloton: ${ip.short} class, ${ip.mins} min` : `Tread: ${ip.text}, ${ip.mins} min`;
  }
  return `${s.walkShort} ${s.walkMin} min`;
}
function trainTitle(r, pl, k) {
  if (r.id === "lift") return `Lift · ${WORKOUTS[pl.sch.lift].name}`;
  if (r.id === "intervals") return intervalPlan(k).mode === "bike" ? "Peloton bike" : "Tread run/walk";
  return r.title.replace(/ · .*$/, "");
}

/* ---------- the due rule ----------
   dueNotifications({settings, day, prevDay?, nowISO, tz, lead?, windowMin?}) → [{key,date,id,category,title,body,tag,url,at,due}]
   - settings: raw `settings` doc; day: raw day doc for today in tz (d-YYYY-MM-DD); prevDay: yesterday's (only for
     schedules running past midnight).
   - A schedule item is due when (item time − lead) falls in (now − windowMin, now], in the user's local wall time.
   - Water nudges (11:00, 15:00) and the evening log (20:30) are fixed clock times (no lead).
   - Done items, pre-program days and disabled categories send nothing. key = "date:itemId" (dedup via push_log). */
function dueNotifications(opts) {
  const o = opts || {};
  const settings = isObj(o.settings) ? o.settings : {};
  const tz = safeTz(o.tz);
  const now = __toDate(o.nowISO);
  const prefs = notifyPrefs(settings), L = leadOf(settings, o.lead);
  const W = Math.max(1, Math.min(60, +o.windowMin || 6));
  if (!prefs.enabled) return [];
  const { key: k, min: m } = tzParts(now, tz);
  const yk = addDays(k, -1);
  setState(settings, { [k]: o.day || {}, [yk]: o.prevDay || {} });
  const out = [];
  collect(k, m);              // today's items
  collect(yk, m + 1440);      // yesterday's items scheduled after midnight (late bedtimes)
  return out.sort((a, b) => a.at.localeCompare(b.at) || a.id.localeCompare(b.id));

  function collect(day, nowM) {
    const pl = planFor(day);
    if (pl.pre) return;
    const d = getDay(day), rows = timeline(day), R = {};
    rows.forEach((r) => { R[r.id] = r; });
    const inWin = (t) => t > nowM - W && t <= nowM;
    const lt = L > 0 ? `In ${L} min` : "Now";
    const ttl = (name, t) => `${lt}: ${name} (${fmt12(t)})`;
    const checked = (id) => !!(d.checks && d.checks[id]);
    const add = (id, category, title, body, dueMin, url) => out.push({
      key: `${day}:${id}`, date: day, id, category, title, body, tag: `ll-${day}-${id}`, url: url || "./#today",
      due: hm(dueMin), at: localToUtc(day, dueMin, tz).toISOString(),
    });

    // training: one notice per contiguous block (lift → intervals → walk), at the block's start
    const tr = rows.filter((r) => (r.kind === "train" || r.kind === "run") && !r.info);
    const blocks = [];
    tr.forEach((r) => { const b = blocks[blocks.length - 1]; if (b && b[b.length - 1].end === r.t) b.push(r); else blocks.push([r]); });

    rows.forEach((r) => {
      const due = r.t - L;
      if (!inWin(due)) return;
      if (r.kind === "meal" || r.id === "prep") {
        if (!prefs.meals || checked(r.id)) return;
        add(r.id, "meals", ttl(r.title, r.t), r.kind === "meal" ? mealBody(r, d) : r.detail, due, "./#today");
      } else if (r.id === "wake") {
        if (!prefs.weigh || d.weight > 0) return;
        add(r.id, "weigh", ttl("Weigh-in", r.t), "Weigh in after the bathroom, before food.", due, "./#today");
      } else if (r.id === "winddown") {
        if (!prefs.evening || checked("winddown") || checked("lightsout")) return;
        add(r.id, "evening", ttl("Wind down", r.t), r.detail, due, "./#today");
      } else if (r.id === "caffeine") {
        if (!prefs.caffeine) return;
        add(r.id, "caffeine", ttl("Caffeine cutoff", r.t), r.detail, due, "./#today");
      } else if (r.kind === "train" || r.kind === "run") {
        const b = blocks.find((x) => x[0] === r);
        if (!b || !prefs.training || checked(r.id)) return;      // only the block start; skip when it's done
        const body = b.filter((x) => !checked(x.id)).map((x) => trainPart(x, pl, day)).join(", then ");
        add(r.id, "training", ttl(trainTitle(r, pl, day), r.t), body || r.detail, due, "./#train");
      }
    });

    if (nowM >= 1440) return;   // fixed-time nudges belong to today only
    const tg = targetsFor(day), wake = R.wake.t, bed = R.lightsout.t;
    // water nudges: logged water under the pace target (linear from wake to 2 h before bed)
    if (prefs.weigh) WATER_NUDGES.forEach((T) => {
      if (!inWin(T) || T <= wake || T >= bed) return;
      const frac = Math.min(1, Math.max(0, (T - wake) / Math.max(60, bed - 120 - wake)));
      const pace = Math.round(tg.water * frac), got = d.water || 0;
      if (got >= pace || got >= tg.water) return;
      add(`water${T / 60}`, "weigh", `Water check: ${got} of ${tg.water} oz`, `Aim for about ${pace} oz by ${fmt12(T)}. Drink 16 oz now.`, T, "./#today");
    });
    // evening log: steps, water or sleep not logged yet
    if (prefs.evening && inWin(EVENING_LOG) && EVENING_LOG < bed) {
      const miss = [["steps", "steps"], ["water", "water"], ["sleep", "sleep"]].filter(([f]) => d[f] == null).map(([, n]) => n);
      if (miss.length) {
        const list = miss.length === 1 ? miss[0] : miss.slice(0, -1).join(", ") + " and " + miss[miss.length - 1];
        add("evening", "evening", "Log today", `Not logged yet: ${list}.`, EVENING_LOG, "./#today");
      }
    }
  }
}

export { S, setState, timeline, planFor, habits, targetsFor, dayBrief, getDay, intervalPlan, buildMeals, todayKeyInTz, nowInTz, tzParts, localToUtc, addDays, fmt12, notifyPrefs, leadOf, dueNotifications, NOTIFY_DEFAULTS, DEFAULTS };
"""

def main():
    parts = [PRELUDE.replace("{files}", ", ".join(FILES))]
    for f in FILES:
        src = open(os.path.join(APP_JS, f), encoding="utf-8").read().rstrip("\n")
        parts.append(f"\n/* ======== app/js/{f} ======== */\n{src}\n")
    parts.append(API)
    out = "".join(parts)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(out)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(out):,} bytes)")

if __name__ == "__main__":
    main()
