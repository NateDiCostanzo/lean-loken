"""Bundle the app's program logic into supabase/functions/notify/schedule.js (an ES module for Deno/Node).

The app files are concatenated unchanged, inside module scope, with small stubs for the browser
globals they reference. A server API (setState, dueNotifications, tz helpers) is appended.

Usage: python3 pwa/build-schedule.py [out_path]
"""
